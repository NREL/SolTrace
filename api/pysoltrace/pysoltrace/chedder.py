_DEFAULT_LITERAL_NS: Dict[str, Any] = {"nullptr": None, "NULL": None, "true": True, "false": False}


def _eval_default_expr(expr: str, ns: Dict[str, any]) -> Tuple[Any, bool]:
    """Try to evaluate a C++ default member initializer expression
    ('= DEFAULT_NUM_THREADS', '= nullptr', '= 0') as a Python value.

    Only numeric/boolean/nullptr literals and names matching a known enum
    member are supported -- this module doesn't parse '#define' macros, so
    an unresolvable name (like a project-specific macro constant) is
    reported as unresolved rather than guessed at. Returns (value, True) on
    success, (None, False) if the expression couldn't be resolved."""
    try:
        return eval(expr, {"__builtins__": {}}, ns), True # noqa: S307
    except Exception:
        return None, False


def _parse_field_stmt(stmt: str) -> List[Tuple[str, str, Optional[str]]]:
    """Parse one struct/union field statement (no trailing ';') into a list
    of (field_name, type_str, default_expr_or_None). Handles:
      - C++ default member initializers: 'uint_fast64_t n = DEFAULT_N'
      - pointer defaults: 'st_uint_t *seeds = nullptr'
      - comma-separated declarators sharing a type: 'int a, b;'
        (a default on one declarator does not propagate to siblings)
    A comma inside the default expression itself (e.g. a macro call taking
    multiple arguments) isn't handled -- documented limitation, rare in
    practice for a default-member-initializer expression."""
    results: List[Tuple[str, str, Optional[str]]] = []
    parts = [p.strip() for p in stmt.split(",")]
    shared_type: Optional[str] = None
    for idx, part in enumerate(parts):
        default_expr: Optional[str] = None
        if "=" in part:
            decl, default_expr = part.split("=", 1)
            decl, default_expr = decl.strip(), default_expr.strip()
        else:
            decl = part
        if idx == 0:
            split = _split_type_and_name(decl)
            if split is None:
                warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                              f"could not parse struct field '{stmt}'; "
                              f"skipping it (this may misalign the ctypes "
                              f"layout for the rest of the struct).",
                              stacklevel=2)
                return results
            shared_type, name = split
            field_type = shared_type
        else:
            ptr_prefix = ""
            nm = decl
            while nm.startswith("*"):
                ptr_prefix += "*"
                nm = nm[1:].strip()
            if shared_type is None or not _IDENTIFIER_RE.match(nm):
                warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                              f"could not parse struct field "
                              f"'{part}' in '{stmt}'; skipping it.",
                              stacklevel=2)
                continue
            name = nm
            field_type = f"{shared_type} {ptr_prefix}".strip() if ptr_prefix else shared_type
        results.append((name, field_type, default_expr))
    return results


def _parse_compound_body(body: str) -> List[Tuple]:
    """Recursively parse a struct/union body into an ordered member list.
    Each member is one of:
        ('field', name, type_str, default_expr_or_None)
        ('compound', name_or_None, kind, nested_member_list)
    `name` is None for a genuinely anonymous nested struct/union member (no
    field name given before the ';') -- its members get hoisted onto the
    parent via ctypes' `_anonymous_` mechanism when this is built into a
    class, mirroring C++ semantics."""
    members: List[Tuple] = []
    i, n = 0, len(body)
    while i < n:
        while i < n and body[i].isspace():
            i += 1
        if i >= n:
            break
        m = _COMPOUND_OPEN_RE.match(body, i)
        if m:
            kind = m.group("kind")
            open_idx = m.end() - 1
            close_idx = _find_matching_brace(body, open_idx)
            if close_idx is None:
                warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                              f"unterminated nested {kind} body; "
                              f"skipping the rest of this member list.",
                              stacklevel=2)
                break
            inner_body = body[open_idx + 1:close_idx]
            nested_members = _parse_compound_body(inner_body)

            name_match = _NAME_SEMI_RE.match(body, close_idx + 1)
            if name_match:
                members.append(("compound", name_match.group("name"), kind, nested_members))
                i = name_match.end()
            else:
                # No identifier before ';' -> anonymous nested member.
                anon_end = body.find(";", close_idx + 1)
                trailing = body[close_idx + 1:anon_end].strip() if anon_end != -1 else ""
                if trailing:
                    warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                                  f"chedder: could not parse nested {kind} "
                                  f"member declarator '{trailing}'; skipping.",
                                  stacklevel=2)
                else:
                    members.append(("compound", None, kind, nested_members))
                i = (anon_end + 1) if anon_end != -1 else n
            continue

        semi_idx = body.find(";", i)
        if semi_idx == -1:
            break
        stmt = body[i:semi_idx].strip()
        i = semi_idx + 1
        if not stmt:
            continue
        members.extend(
            ("field", fname, ftype, fdefault)
            for fname, ftype, fdefault in _parse_field_stmt(stmt)
        )
    return members


class _ParsedHeader:
    __slots__ = (
        "defines",
        "enums",
        "enum_underlying",
        "funcptrs",
        "typedefs",
        "path",
        "structs"
    )

    def __init__(self,
                 defines: Dict[str, any],
                 enums: Dict[str, Dict[str, int]],
                 enum_underlying: Dict[str, Optional[str]],
                 funcptrs: Dict[str, Tuple[str, List[str]]],
                 typedefs: Dict[str, str],
                 structs: Dict[str, Tuple[Optional[str], str, List[Tuple]]]):
        self.defines = defines
        self.enums = enums
        self.enum_underlying = enum_underlying
        self.funcptrs = funcptrs
        self.typedefs = typedefs
        # name -> (tag, kind, member_list); kind is "struct" or "union";
        # member_list is the recursive structure _parse_compound_body
        # produces (see its docstring).
        self.structs = structs


def _type_label(ctype: Any) -> str:
    """Short human-readable label for a ctypes/enum type -- used when we're
    not expanding it further (base ctypes types have no sub-structure to
    expand)."""
    if ctype is None:
        return "void"
    return getattr(ctype, "__name__", None) or repr(ctype)
 
 
def _describe_member(name: str,
                     value: Any,
                     value_to_name: Dict[int, str],
                     seen: frozenset,
                     indent: str = "",
                     depth: int = 0) -> List[str]:
    """Recursively describe one member. If `value` (after unwrapping any
    pointer layers) is itself present in `value_to_name` -- i.e. it's
    another member of the same HeaderDefs, whether that's a struct/union
    field referencing a named struct/enum, or a typedef aliasing another
    named type directly -- it gets expanded in place (fields, enum
    members, etc.) rather than just named. `seen` breaks a self-reference
    (e.g. a linked-list node's own pointer-to-itself field) by printing a
    plain reference instead of expanding again once a type reappears
    within its own expansion chain."""
    _name = Fore.MAGENTA + name

    if depth > 1: return [f"{indent}{_name}{Style.RESET_ALL}: {Fore.RED}{_type_label(value)}{Style.RESET_ALL}"]
    
    ptr_prefix = ""
    target = value
    while isinstance(target, type) and issubclass(target, ctypes._Pointer):
        ptr_prefix += "*"
        target = getattr(target, "_type_", None)
    suffix = f" {ptr_prefix}" if ptr_prefix else ""
    suffix += Style.RESET_ALL
 
    if isinstance(target, type) and issubclass(target, enum.IntEnum):
        members_desc = ", ".join(f"{m.name}={m.value}" for m in target)
        ctype = getattr(target, "_ctype_", ctypes.c_int)
        return [f"{indent}{_name}{suffix}: {Fore.RED}enum {{{members_desc}}} [ctype={_type_label(ctype)}]"]
 
    if isinstance(target, type) and issubclass(target, (ctypes.Structure, ctypes.Union)):
        kind = f'{Fore.RED}{"union" if issubclass(target, ctypes.Union) else "struct"}'
        tid = id(target)
        if tid in seen:
            canonical = value_to_name.get(tid, target.__name__)
            return [f"{indent}{_name}{suffix}: {kind} {target.__name__}{Style.RESET_ALL} (already expanded above, see '{canonical}')"]
        lines = [f"{indent}{_name}{suffix}: {kind}{Style.RESET_ALL} {{"]
        applied = getattr(target, "_field_defaults_", {})
        unresolved = getattr(target, "_unresolved_defaults_", {})
        anon = set(getattr(target, "_anonymous_", ()))
        for fname, fctype, *_rest in getattr(target, "_fields_", []):
            field_label = f"{fname} (anonymous)" if fname in anon else fname
            if fname in applied:
                field_label += f" = {applied[fname]!r}"
            elif fname in unresolved:
                field_label += f" = {unresolved[fname]} (unresolved)"
            lines.extend(
                _describe_member(field_label,
                                 fctype,
                                 value_to_name,
                                 seen | {tid},
                                 indent + "    ",
                                 depth + 1)
            )
        if not getattr(target, "_fields_", []):
            lines.append(f"{indent}    (empty)")
        lines.append(f"{indent}}}")
        return lines
 
    if isinstance(target, type) and issubclass(target, ctypes._CFuncPtr):
        restype = getattr(target, "_restype_", None)
        argtypes = getattr(target, "_argtypes_", ())
        arg_desc = ", ".join(_type_label(a) for a in argtypes) or "void"
        return [f"{indent}{_name}{Style.RESET_ALL}: {Fore.RED}function pointer ({arg_desc}){Style.RESET_ALL} -> {_type_label(restype)}"]
 
    # Plain ctypes simple type (or unresolved/opaque placeholder). Still
    # note when it's literally the same object as another named member
    # (e.g. two typedefs both aliasing the same base ctype).
    label = f'{Fore.RED}{_type_label(target)}{Style.RESET_ALL}'
    same_as = value_to_name.get(id(target)) if target is not None else None
    if same_as and same_as != name:
        return [f"{indent}{_name}{suffix}: {label}  (same as '{same_as}')"]
    return [f"{indent}{_name}{suffix}: {label}"]
 
 
def found_in(header_defs: type) -> str:
    """Return a flat, human-readable listing of everything found in the
    header and exposed on `header_defs` (typically HeaderDefs) -- plain
    typedefs, enums, structs/unions, and function pointer types together,
    in declaration order, with no typedef/enum/struct grouping.
 
    Introspects `header_defs` itself rather than this module's internal
    parse state, so it also works correctly on a class returned by
    reload_header_defs() rather than only the module-level HeaderDefs.
 
    A member whose value is itself another member of `header_defs` -- a
    typedef that directly aliases another named type
    (`typedef empty_args args_st_sim_run_v2;`), or a struct/union field
    whose type is itself a named struct/union/enum exposed on
    `header_defs`, including through a pointer (`node_t* head;`) -- is
    expanded inline instead of just being named.
 
    Usage:
        from cheader_bindings import HeaderDefs, found_in
        print(found_in(HeaderDefs))
    """
    members = {k: v for k, v in vars(header_defs).items() if not k.startswith("__")}
    value_to_name: Dict[int, str] = {}
    for k, v in members.items():
        value_to_name.setdefault(id(v), k)
 
    lines: List[str] = []
    for name, value in sorted(members.items()):
        lines.extend(_describe_member(name, value, value_to_name, frozenset()))

    header = f"Parsed header: {locate_header().name}"
    header += f"\n{'-' * len(header)}\n"
    return header + "\n".join(lines)

def _should_append(name: str, names: list[str] = []):
    return len(names) == 0 or name in names

def _append_defines(defines: Dict[str, any], match: re.Match[str], names: list[str] = []):
    name = match.group("name")
    if not _should_append(name, names): return
    defines[name] = _parse_define_value(match.group("value"))

def _append_enums(enums:           Dict[str, Dict[str, int]],
                  enum_underlying: Dict[str, Optional[str]],
                  match:           re.Match[str],
                  names:           list[str] = []):
    name = match.group("name")
    if name == None: name = match.group("tag")
    if not _should_append(name, names): return

    enums[name] = _parse_enum_body(match.group("body"))
    underlying = match.group("underlying")
    enum_underlying[name] = underlying.strip() if underlying else None

def _append_funcptrs(funcptrs: Dict[str, Tuple[str, List[str]]],
                     match:    re.Match[str],
                     names:    list[str] = []):
    name = match.group("name")
    if not _should_append(name, names): return

    ret = match.group("ret").strip()
    args = _parse_funcptr_args(match.group("args"))
    funcptrs[name] = (ret, args)

def _append_typedefs(typedefs: Dict[str, str],
                     match:    re.Match[str],
                     names:    list[str] = []):
    split = _split_type_and_name(match.group("rest"))
    if split is None: return 

    type_str, name = split
    if not _should_append(name, names): return

    typedefs[name] = type_str

def _append_structs(structs:     Dict[str, Tuple[Optional[str], str, List[Tuple]]],
                    cleaned_txt: str,
                    match:       re.Match[str],
                    names:       list[str] = []):
    kind = match.group("kind")
    tag = match.group("tag")
    open_idx = match.end() - 1
    close_idx = _find_matching_brace(cleaned_txt, open_idx)
    if close_idx is None:
        warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                        f"unterminated {kind} body near offset "
                        f"{match.start()}; skipping.",
                        stacklevel=2)
        return
    
    name_match = _NAME_SEMI_RE.match(cleaned_txt, close_idx + 1)
    if not name_match:
        warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                        f"could not find a typedef alias name "
                        f"for the {kind} near offset {match.start()}; skipping.",
                        stacklevel=2)
        return
    
    name = name_match.group("name")
    if not _should_append(name, names): return

    inner_body = cleaned_txt[open_idx + 1:close_idx]
    members = _parse_compound_body(inner_body)
    structs[name] = (tag, kind, members)

def _parse_header_text(header_path: Path) -> _ParsedHeader:
    text = header_path.read_bytes().decode("utf-8", errors="replace")
    clean = _strip_comments(text)

    defines: Dict[str, any] = {}
    for match in _DEFINE_RE.finditer(clean):
        _append_defines(defines, match)

    enums: Dict[str, Dict[str, int]] = {}
    enum_underlying: Dict[str, Optional[str]] = {}
    for match in _ENUM_RE.finditer(clean):
        _append_enums(enums, enum_underlying, match)

    funcptrs: Dict[str, Tuple[str, List[str]]] = {}
    for match in _FUNCPTR_RE.finditer(clean):
        _append_funcptrs(funcptrs, match)

    typedefs: Dict[str, str] = {}
    for match in _TYPEDEF_RE.finditer(clean):
        _append_typedefs(typedefs, match)

    structs: Dict[str, Tuple[Optional[str], str, List[Tuple]]] = {}
    for match in _STRUCT_HEADER_RE.finditer(clean):
        _append_structs(structs, clean, match)

    return _ParsedHeader(defines,
                         enums,
                         enum_underlying,
                         funcptrs,
                         typedefs,
                         structs)

def _append_extras(_parsed: _ParsedHeader, _extra: header_values):
    text = _extra.path.read_bytes().decode("utf-8", errors="replace")
    clean = _strip_comments(text)

    if len(_extra.values['defines']):
        for match in _DEFINE_RE.finditer(clean):
            _append_defines(_parsed.defines,
                            match,
                            _extra.values['defines'])

    if len(_extra.values['enums']):
        for match in _ENUM_RE.finditer(clean):
            _append_enums(_parsed.enums,
                          _parsed.enum_underlying,
                          match,
                          _extra.values['enums'])

    if len(_extra.values['funcptrs']):
        for match in _FUNCPTR_RE.finditer(clean):
            _append_funcptrs(_parsed.funcptrs,
                             match,
                             _extra.values['funcptrs'])

    if len(_extra.values['typedefs']):
        for match in _TYPEDEF_RE.finditer(clean):
            _append_typedefs(_parsed.typedefs,
                             match,
                             _extra.values['typedefs'])

    if len(_extra.values['structs']):
        for match in _STRUCT_HEADER_RE.finditer(clean):
            _append_structs(_parsed.structs,
                            clean,
                            match,
                            _extra.values['structs'])

