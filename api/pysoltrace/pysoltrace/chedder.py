def _make_struct_init(base: type, defaults: Dict[str, Any], field_order: List[str]):
    """Build an __init__ that applies resolved C++ default member
    initializers for any field the caller doesn't explicitly supply
    (positionally or by keyword), then delegates to the real ctypes
    __init__. Only attached to classes with at least one resolved
    default, so structs without defaults pay zero extra overhead per
    instantiation -- important if you're constructing these in bulk
    inside a list comprehension."""
    def __init__(self, *args, **kwargs):
        covered = set(field_order[: len(args)]) | set(kwargs.keys())
        for fname, value in defaults.items():
            if fname not in covered:
                kwargs[fname] = value
        base.__init__(self, *args, **kwargs)
    return __init__

def _make_struct_value(_struct: type):
    @property
    def value(self):
        return { field[0]: _f.value 
                           if hasattr(_f := getattr(self, field[0]), 'value') else 
                           _f 
                 for field in _struct._fields_ }
    return value

def _build_namespace(parsed: _ParsedHeader, class_name: str = "dot_h") -> type:
    # Flatten every enum member name -> int value up front (independent of
    # when/whether the IntEnum classes themselves get built), so default
    # member initializers that reference an enum constant can resolve.
    enum_value_ns: Dict[str, int] = {}
    for members_dict in parsed.enums.values():
        enum_value_ns.update(members_dict)

    # Step 1: create bare struct/union class shells (no _fields_ yet) before
    # resolving anything else. This is what makes self-referential fields
    # work ('struct node_s* next;' inside node_s itself, for a linked-list
    # node) and lets any struct's field reference any other struct defined
    # anywhere in the header, regardless of declaration order -- ctypes
    # only needs the class object to exist to build a POINTER() to it or
    # use it as a field type, not its _fields_ yet.
    struct_ctypes: Dict[str, Any] = {}
    struct_classes: Dict[str, type] = {}
    for name, (tag, kind, _members) in parsed.structs.items():
        base = ctypes.Union if kind == "union" else ctypes.Structure
        cls = type(name, (base,), {})
        struct_classes[name] = cls
        struct_ctypes[name] = cls
        if tag and tag != name:
            struct_ctypes[tag] = cls

    # Step 2: resolve every plain typedef down to a concrete ctypes type,
    # following alias chains (st_return_t -> st_uint_t -> unsigned int) and
    # struct-to-struct aliases (typedef empty_args args_st_sim_run_v2;).
    # resolved_typedefs doubles as the memoization cache: _resolve_ctype
    # writes every intermediate alias it walks into it, so a chain of
    # depth N is only ever traversed once total across this whole build,
    # no matter how many typedefs/enums/structs/funcptrs reference it.
    resolved_typedefs: Dict[str, Any] = {}
    for name in parsed.typedefs:
        if name not in resolved_typedefs:
            resolved_typedefs[name] = _resolve_ctype(parsed.typedefs[name], 
                                                     parsed.typedefs, 
                                                     {}, 
                                                     resolved_typedefs,
                                                     frozenset({name}), 
                                                     struct_ctypes)

    # Step 3: each enum's underlying ctype: explicit 'enum NAME : UNDERLYING'
    # if the header gave one (itself possibly a typedef chain, resolved via
    # the same memoized cache above), else plain c_int.
    resolved_enum_ctypes: Dict[str, Any] = {}
    for name, underlying_str in parsed.enum_underlying.items():
        if underlying_str:
            resolved_enum_ctypes[name] = _resolve_ctype(underlying_str, 
                                                        parsed.typedefs, 
                                                        {}, 
                                                        resolved_typedefs,
                                                        frozenset(), 
                                                        struct_ctypes)
        else:
            resolved_enum_ctypes[name] = ctypes.c_int

    # Step 4: now that typedefs, enums, and every struct/union name are
    # resolvable, recursively build each struct/union's fields (including
    # nested anonymous/named struct or union members) and apply any
    # resolvable default member initializers.
    def build_fields(owner_name: str, members: List[Tuple]):
        """Returns (ctypes_fields, applied_defaults, unresolved_defaults,
        anonymous_field_names) for one struct/union's member list,
        recursing into nested compound members as needed."""
        ctypes_fields: List[Tuple[str, Any]] = []
        applied_defaults: Dict[str, Any] = {}
        unresolved_defaults: Dict[str, str] = {}
        anon_names: List[str] = []

        default_expr_ns = {**_DEFAULT_LITERAL_NS, **enum_value_ns,  **parsed.defines}

        for idx, member in enumerate(members):
            if member[0] == "field":
                _, fname, type_str, default_expr = member
                field_ctype = _resolve_ctype(type_str,
                                             parsed.typedefs,
                                             resolved_enum_ctypes,
                                             resolved_typedefs,
                                             frozenset(),
                                             struct_ctypes)
                ctypes_fields.append((fname, field_ctype if field_ctype is not None else ctypes.c_void_p))
                if default_expr is not None:
                    value, ok = _eval_default_expr(default_expr, default_expr_ns)
                    if ok:
                        applied_defaults[fname] = value
                    else:
                        unresolved_defaults[fname] = default_expr
            else:  # "compound" -- nested struct/union member
                _, cname, kind, nested_members = member
                anonymous = cname is None
                field_name = cname or f"_anon_{idx}"
                nested_base = ctypes.Union if kind == "union" else ctypes.Structure
                nested_owner = f"{owner_name}__{field_name}"
                nested_cls = type(nested_owner, (nested_base,), {})
                (nested_fields, nested_applied, nested_unresolved,
                 nested_anon) = build_fields(nested_owner, nested_members)
                if nested_anon:
                    nested_cls._anonymous_ = tuple(nested_anon)
                nested_cls._fields_ = nested_fields
                nested_cls._field_defaults_ = nested_applied
                nested_cls._unresolved_defaults_ = nested_unresolved
                nested_cls.value = _make_struct_value(nested_cls)
                if nested_applied:
                    nested_cls.__init__ = _make_struct_init(nested_base,
                                                            nested_applied, 
                                                            [f[0] for f in nested_fields])
                ctypes_fields.append((field_name, nested_cls))
                if anonymous:
                    anon_names.append(field_name)

        return ctypes_fields, applied_defaults, unresolved_defaults, anon_names

    for name, (_tag, kind, members) in parsed.structs.items():
        fields, applied, unresolved, anon = build_fields(name, members)
        cls = struct_classes[name]
        if anon:
            cls._anonymous_ = tuple(anon)
        cls._fields_ = fields
        cls._field_defaults_ = applied
        cls._unresolved_defaults_ = unresolved
        cls.value = _make_struct_value(cls)
        if applied:
            base = ctypes.Union if kind == "union" else ctypes.Structure
            cls.__init__ = _make_struct_init(base,
                                             applied,
                                             [f[0] for f in fields])

    enum_classes: Dict[str, type] = {}
    for name, members in parsed.enums.items():
        enum_cls = enum.IntEnum(name, members)
        enum_cls._ctype_ = resolved_enum_ctypes[name]  # type: ignore[attr-defined]
        enum_classes[name] = enum_cls

    funcptr_types: Dict[str, type] = {}
    for name, (ret_str, arg_strs) in parsed.funcptrs.items():
        ret_ctype = (
            _resolve_ctype(ret_str,
                           parsed.typedefs,
                           resolved_enum_ctypes,
                           resolved_typedefs,
                           frozenset(), 
                           struct_ctypes)
            if ret_str and ret_str != "void"
            else None
        )
        arg_ctypes = [
            _resolve_ctype(_strip_param_name(a),
                           parsed.typedefs,
                           resolved_enum_ctypes,
                           resolved_typedefs,
                           frozenset(),
                           struct_ctypes)
            for a in arg_strs
        ]
        funcptr_types[name] = ctypes.CFUNCTYPE(ret_ctype, *arg_ctypes)

    namespace = {
        'DEFINES': [*parsed.defines.keys()],
        'TYPEDEFS': [*resolved_typedefs.keys()],
        'STRUCTS': [*struct_classes.keys()],
        'ENUMS': [*enum_classes.keys()],
        'FUNCPTRS': [*funcptr_types.keys()],
        **parsed.defines,
        **resolved_typedefs,
        **struct_classes,
        **enum_classes,
        **funcptr_types,
        "__slots__": ()
    }
    return type(class_name, (object,), namespace)

def reload_header_defs(header_filename: str = _HEADER_FILENAME) -> type:
    """Re-locate and re-parse the header. Rebinds the module-level
    dot_h to the freshly built class and returns it -- useful for
    development iteration when the header changes between calls within
    the same process; normal usage should just import dot_h."""
    header_path = locate_header(header_filename)
    parsed = _parse_header_text(header_path)
    global dot_h
    dot_h = _build_namespace(parsed)
    return dot_h


