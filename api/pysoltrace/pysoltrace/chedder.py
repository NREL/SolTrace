_WS_RE = re.compile(r"\s+")
_QUALIFIER_RE = re.compile(r"\b(const|volatile|struct|union)\b")
_IDENTIFIER_RE = re.compile(r"^[A-Za-z_]\w*$")
_ARRAY_RE = re.compile(r"^[A-Za-z_]\w*\[[0-9]*\]$")
_ARRAY_LENGTH_RE = re.compile(r"^(?P<type>[A-Za-z_]+)\s*\[\w*(?P<length>[0-9]+)\w*\]$")

def _strip_param_name(arg: str) -> str:
    """Turn 'const char* message' / 'int count' into just the type part,
    while leaving bare types like 'unsigned int' or 'StatusCode' untouched."""
    s = re.sub(r"\*", " * ", arg.strip())
    tokens = s.split()
    if len(tokens) <= 1:
        return arg.strip()
    last = tokens[-1]
    if last == "*" or last in ("const", "volatile"):
        return arg.strip()
    if _IDENTIFIER_RE.match(last) and last not in _BASE_CTYPES:
        tokens = tokens[:-1]
        return " ".join(tokens)
    return arg.strip()


def _split_type_and_name(rest: str) -> Optional[Tuple[str, str]]:
    """Split a declaration's body ('unsigned int st_uint_t') into
    (type_str, alias_name). Returns None if it doesn't look like a valid
    'TYPE NAME' declaration (e.g. malformed input)."""
    s = re.sub(r"\*", " * ", rest.strip())
    tokens = s.split()
    if len(tokens) < 2:
        return None
    name = tokens[-1]
    type_str = " ".join(tokens[:-1])
    if _ARRAY_RE.match(name):
        temp = _ARRAY_LENGTH_RE.match(name)
        return f'{type_str}[{temp.group("length")}]', name[:-3]
    if not _IDENTIFIER_RE.match(name):
        return None
    return type_str, name


def _resolve_ctype(type_str: str,
                   typedef_raw: Dict[str, str],
                   enum_ctypes: Dict[str, Any],
                   resolved_cache: Dict[str, Any],
                   _stack: frozenset = frozenset(),
                   struct_ctypes: Optional[Dict[str, Any]] = None):
    """Map a C type string to a ctypes type.

    This is the recursive, memoized alias resolver: when `base` turns out
    to itself be another typedef name, it recurses one link down the chain
    and -- critically -- stores the result in `resolved_cache` before
    returning, so that name never has to be walked again for the rest of
    this build (every later reference, from any other typedef, enum
    underlying-type clause, struct field, or function-pointer signature,
    hits the cache in O(1) instead of re-resolving the chain). `_stack`
    guards against cyclic typedefs (A -> B -> A) turning into infinite
    recursion.

    `struct_ctypes` maps struct/union tag names *and* their typedef alias
    names to the already-created (possibly still field-less) ctypes class,
    so 'struct node_s *' inside another struct's own field list resolves
    correctly -- including the pointer-to-self case a linked-list node
    needs, since the class object exists before its `_fields_` are filled,
    and so a typedef-of-a-struct ('typedef empty_args other_name;')
    resolves to that same generated class.
    """
    struct_ctypes = struct_ctypes or {}
    s = _QUALIFIER_RE.sub("", type_str).strip()
    ptr_count = s.count("*")
    s = _WS_RE.sub(" ", s.replace("*", " ")).strip()
    base = s

    def ptr_wrap(type, count):
        for _ in range(count): type = ctypes.POINTER(type)
        return type 

    if base == "void":
        if ptr_count == 0:
            return None
        return ptr_wrap(ctypes.c_void_p, ptr_count - 1)

    if base == "char" and ptr_count == 1:
        return ctypes.c_char_p

    if base in _stack:
        warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                      f"cyclic typedef chain detected at '{base}'; "
                      f"treating as opaque void*-sized value.",
                      stacklevel=2)
        ctype = ctypes.c_void_p
    elif base in resolved_cache:
        # Memoization hit -- this alias's chain was already walked.
        ctype = resolved_cache[base]
    elif base in enum_ctypes:
        ctype = enum_ctypes[base]
    elif base in struct_ctypes:
        ctype = struct_ctypes[base]
    elif (match := _ARRAY_LENGTH_RE.match(base)):
        arr_type, arr_length = match.group("type"), int(match.group("length"))
        ctype = ctypes.c_void_p
        if arr_type in enum_ctypes:
            ctype = enum_ctypes[arr_type] * arr_length
        elif arr_type in struct_ctypes:
            ctype = struct_ctypes[arr_type] * arr_length
        elif arr_type in typedef_raw:
            temp = _resolve_ctype(typedef_raw[arr_type], 
                               typedef_raw, 
                               enum_ctypes, 
                               resolved_cache,
                               _stack | {arr_type}, 
                               struct_ctypes)
            ctype = temp * arr_length
        elif arr_type in _BASE_CTYPES and _BASE_CTYPES[arr_type] is not None:
            ctype = _BASE_CTYPES[arr_type] * arr_length

        if ctype == ctypes.c_void_p:
            warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                          f"unknown array type '{type_str}', "
                          f"treating as opaque void*-sized value.",
                          stacklevel=2)

        resolved_cache[base] = ctype  # memoize before returning
    elif base in typedef_raw:
        ctype = _resolve_ctype(typedef_raw[base], 
                               typedef_raw, 
                               enum_ctypes, 
                               resolved_cache,
                               _stack | {base}, 
                               struct_ctypes)
        resolved_cache[base] = ctype  # memoize before returning
    elif base in _BASE_CTYPES and _BASE_CTYPES[base] is not None:
        ctype = _BASE_CTYPES[base]
    else:
        # Unknown / opaque type (forward-declared struct not defined
        # anywhere in this header, etc.) -- treat as an opaque
        # pointer-sized handle; this keeps parsing resilient instead of
        # failing the whole header on one exotic or externally-defined type.
        if ptr_count == 0:
            warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                          f"unknown non-pointer type '{type_str}', "
                          f"treating as opaque void*-sized value.",
                          stacklevel=2)
        ctype = ctypes.c_void_p
        ptr_count = max(ptr_count - 1, 0)

    return ptr_wrap(ctype, ptr_count)


