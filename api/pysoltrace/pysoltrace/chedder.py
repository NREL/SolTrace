# typedef RET (*NAME)(ARGS);
_FUNCPTR_RE = re.compile(
    r"typedef\s+(?P<ret>[A-Za-z_][\w\s]*?\**)\s*\(\s*\*\s*(?P<name>[A-Za-z_]\w*)\s*\)"
    r"\s*\(\s*(?P<args>[^)]*)\)\s*;",
)

# typedef TYPE NAME;  (plain aliases, incl. chains like 'typedef st_uint_t st_return_t;'
# and struct-to-struct aliases like 'typedef empty_args args_st_sim_run_v2;')
# Structurally can't match enum/funcptr/struct/union statements since those
# always contain a '{' or '(' before their terminating ';'; 'enum' is
# excluded explicitly too, to skip brace-less forward-declaration forms
# like 'typedef enum Foo Bar;' which conceptually belong with _ENUM_RE.
_TYPEDEF_RE = re.compile(r"typedef\s+(?!enum\b)(?P<rest>[^;{}()\[\]]+?)\s*;")

# Struct/union bodies CAN contain nested braces (nested anonymous unions,
# etc.), which a regex character class can't express with proper nesting.
# So structs/unions are found in two steps: this regex locates just the
# opening "typedef struct|union [TAG] {", then _find_matching_brace() walks
# forward from there to find the real matching close brace by depth.
_STRUCT_HEADER_RE = re.compile(
    r"typedef\s+(?P<kind>struct|union)\s*(?:(?P<tag>[A-Za-z_]\w*)\s*)?\{"
)
# A nested (non-typedef) struct/union member opening, found while walking a
# body: e.g. 'union {' or 'struct node_s {' inside another struct's body.
_COMPOUND_OPEN_RE = re.compile(r"(?P<kind>struct|union)\b\s*(?:[A-Za-z_]\w*)?\s*\{")
# An identifier + ';' immediately following a compound's closing brace,
# e.g. '} payload;' or '} args_st_sim_setup;'.
_NAME_SEMI_RE = re.compile(r"\s*(?P<name>[A-Za-z_]\w*)\s*;")


def _find_matching_brace(text: str, open_idx: int) -> Optional[int]:
    """Given the index of an opening '{' in text, return the index of its
    matching closing '}' by simple depth counting. Returns None if
    unterminated. (Doesn't account for braces inside string/char literals
    -- essentially never seen inside a struct/union body in practice.)"""
    depth = 0
    for i in range(open_idx, len(text)):
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
    return None


def _strip_comments(text: str) -> str:
    return _COMMENT_RE.sub(" ", text)

def _parse_define_value(value: str) -> any:
    expr = value.strip()
    if not len(expr): return None
    try:
        return eval(expr, {"__builtins__": {}}, {})  # noqa: S307
    except Exception:
        warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                      f"could not evaluate #define expression '{expr}'.",
                      stacklevel=2)
        return expr

def _parse_enum_body(body: str) -> Dict[str, int]:
    members: Dict[str, int] = {}
    next_value = 0
    for raw_entry in body.split(","):
        entry = raw_entry.strip()
        if not entry:
            continue
        if "=" in entry:
            name, expr = entry.split("=", 1)
            name = name.strip()
            expr = expr.strip()
            try:
                value = eval(expr, {"__builtins__": {}}, dict(members))  # noqa: S307
            except Exception:
                warnings.warn(f"{Fore.YELLOW}[chedder] - warning{Style.RESET_ALL}: "
                              f"could not evaluate enum expression "
                              f"'{expr}' for member '{name}'; using auto-increment.",
                              stacklevel=2)
                value = next_value
        else:
            name = entry
            value = next_value
        members[name] = value
        next_value = value + 1
    return members


def _parse_funcptr_args(args: str) -> List[str]:
    args = args.strip()
    if args == "" or args == "void":
        return []
    return [a.strip() for a in args.split(",")]


